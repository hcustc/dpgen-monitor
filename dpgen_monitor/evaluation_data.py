from __future__ import annotations

from pathlib import Path


PREVIOUS_ITERATION_TEST_DATA = (
    "data.iters/iter.{previous_iteration:06d}/02.fp/data.000"
)
CURRENT_ITERATION_FP_DATA = "../02.fp/data.000"
INITIAL_TEST_DATA = "data.init/03.data"


def resolve_evaluation_data(
    train_dir: str | Path,
    iteration: int,
    test_data: str = PREVIOUS_ITERATION_TEST_DATA,
    initial_test_data: str = INITIAL_TEST_DATA,
) -> Path:
    """Resolve the dataset used to evaluate an iteration's trained models.

    Iteration N>0 defaults to the labeled data acquired by iteration N-1, which
    is the newest batch incorporated into iteration N's training. Iteration 0
    has no previous batch and therefore uses the configured initial dataset.

    ``test_data`` may use ``{iteration}`` and ``{previous_iteration}`` format
    fields. A literal path remains supported for projects that need a fixed
    benchmark dataset.
    """
    if iteration < 0:
        raise ValueError(f"iteration must be non-negative; got {iteration}")

    template = initial_test_data if iteration == 0 else test_data
    try:
        rendered = template.format(
            iteration=iteration,
            previous_iteration=iteration - 1,
        )
    except (KeyError, ValueError) as exc:
        raise ValueError(f"Invalid evaluation data template: {template!r}") from exc

    path = Path(rendered).expanduser()
    if not path.is_absolute():
        path = Path(train_dir) / path
    return path.resolve(strict=False)


def evaluation_data_description(iteration: int) -> str:
    if iteration == 0:
        return "初始数据回归评估"
    return f"上一轮新增数据吸收评估（iter.{iteration - 1:06d} FP 数据）"


def resolve_current_iteration_fp_data(
    train_dir: str | Path,
    iteration: int,
) -> Path:
    """Resolve the FP labels generated by the same model/DP-GEN iteration."""
    if iteration < 0:
        raise ValueError(f"iteration must be non-negative; got {iteration}")
    return (Path(train_dir) / CURRENT_ITERATION_FP_DATA).resolve(strict=False)


def current_iteration_fp_evaluation_description(iteration: int) -> str:
    """Describe a pre-assimilation evaluation on newly labeled hard cases."""
    if iteration < 0:
        raise ValueError(f"iteration must be non-negative; got {iteration}")
    return f"本轮新增 FP 盲区评估（iter.{iteration:06d} FP 数据）"
